#!/usr/bin/env bash
# Regenerate the exact-pin dependency locks of planning/26-stock-ray-images.md. Needs network and uv (on PATH or via mise).
#
#   scripts/lock.sh
#
# Writes  ray-training/ray_core/requirements.lock   every transitive pin of the core environment (torch, onnx, boto3, ...)
#         task-bundles/tasks/<slug>/manifest.json   the "requirements" field: what the bundle needs beyond the core lock
# core-api installs the union of the two through Ray's uv runtime env, so no package may be pinned differently in them
# (a 409), and the bundles are resolved together so they also agree with each other (a core smoke runs them in one env).
# Ray itself is in the stock image: it is constrained to the cluster's version and never an input, so neither it nor its
# own dependency set lands in a lock. protobuf stays below 6 (ray[serve] pins 5.x, the newest onnx needs 6.31+).
# Add the direct imports of a new bundle to bundle_inputs below; the script refuses a bundle it does not know.
set -euo pipefail
cd "$(dirname "$0")/.."

RAY_VERSION=2.60.0  # k8s apps/ray/app/raycluster.yaml
CORE_LOCK=ray-training/ray_core/requirements.lock
BUNDLES=task-bundles/tasks
CORE_INPUTS=('torch>=2.7,<2.12' torchvision onnx onnxruntime-gpu onnxscript numpy boto3 pyarrow pillow)  # onnxruntime-gpu replaces onnxruntime
FLAGS=(--python-version 3.11 --python-platform x86_64-manylinux_2_28 --extra-index-url https://download.pytorch.org/whl/cu128
       --index-strategy unsafe-best-match)
OUTPUT=(--no-header --no-annotate --quiet)  # a bare name==version per line

bundle_inputs() {  # the packages a bundle imports that the core does not pin; their dependencies are resolved
    case $1 in
        image-classification) echo transformers ;;
        object-detection) echo transformers scipy timm ;;  # scipy: RT-DETR Hungarian matcher; timm: RT-DETR backbones
        text-classification) echo transformers tokenizers ;;
        tabular-classification) echo xgboost onnxmltools ;;
        *) echo "scripts/lock.sh: no inputs for bundle $1, add it to bundle_inputs" >&2; exit 1 ;;
    esac
}

uv_() { if command -v uv >/dev/null; then uv "$@"; else mise exec -- uv "$@"; fi; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
printf 'ray==%s\nprotobuf<6\n' "$RAY_VERSION" > "$tmp/base.txt"

# resolve <out> <constraints file> <requirement>...
resolve() {
    local out=$1 constraints=$2
    shift 2
    printf '%s\n' "$@" > "$tmp/in.txt"
    uv_ pip compile "$tmp/in.txt" -c "$tmp/base.txt" -c "$constraints" "${FLAGS[@]}" "${OUTPUT[@]}" -o "$out"
}

# 1. The core: resolved alone, so a bundle's needs never move its versions.
: > "$tmp/none.txt"
resolve "$tmp/core.txt" "$tmp/none.txt" "${CORE_INPUTS[@]}"
{
    echo "# Exact pins of the ray_core environment (torch, onnx, boto3, ...), installed by Ray's uv runtime env (planning/26)."
    echo "# Generated by scripts/lock.sh on $(date -u +%Y-%m-%d); do not edit. Resolved by:"
    echo "#   uv pip compile <inputs> -c [ray==$RAY_VERSION, protobuf<6] ${FLAGS[*]}"
    echo "# inputs: ${CORE_INPUTS[*]}"
    cat "$tmp/core.txt"
} > "$CORE_LOCK"
echo "$CORE_LOCK: $(grep -vc '^#' "$CORE_LOCK") pins"

# 2. Every bundle's inputs plus the core in one resolve, with the core lock held: the one version of each extra package.
all=()
for dir in "$BUNDLES"/*/; do
    # shellcheck disable=SC2207
    all+=($(bundle_inputs "$(basename "$dir")"))
done
grep -v '^#' "$CORE_LOCK" > "$tmp/core-constraints.txt"
resolve "$tmp/universe.txt" "$tmp/core-constraints.txt" "${CORE_INPUTS[@]}" "${all[@]}"

# 3. Each bundle: its own closure at the universe's versions, minus what the core lock already pins.
for dir in "$BUNDLES"/*/; do
    slug=$(basename "$dir")
    # shellcheck disable=SC2046
    resolve "$tmp/$slug.txt" "$tmp/universe.txt" $(bundle_inputs "$slug")
    python3 - "$dir/manifest.json" "$tmp/$slug.txt" "$tmp/core-constraints.txt" <<'PY'
import json
import sys
from pathlib import Path

manifest, bundle, core = (Path(p) for p in sys.argv[1:])
pins = lambda path: dict(line.split("==", 1) for line in path.read_text().split() if "==" in line)
core_pins = pins(core)
delta = {name: version for name, version in pins(bundle).items() if name not in core_pins}
assert all(core_pins.get(name, version) == version for name, version in pins(bundle).items()), "bundle pin differs from the core lock"
doc = json.loads(manifest.read_text())
doc["requirements"] = [f"{name}=={version}" for name, version in sorted(delta.items())]  # keeps its place if already there, else last
manifest.write_text(json.dumps(doc, indent=2) + "\n")
print(f"{manifest}: {len(delta)} pins")
PY
done
